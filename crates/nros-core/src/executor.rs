/// Realtime lint check — would be `nros check --realtime` per DESIGN.md
/// Inspects callback source for forbidden operations in HardRealtime context
#[derive(Debug, Clone)]
pub struct RealtimeLint {
    pub errors: Vec<String>,
    pub warnings: Vec<String>,
}

impl RealtimeLint {
    pub fn new() -> Self { Self { errors: Vec::new(), warnings: Vec::new() } }

    /// Check if callback contains forbidden operations for HardRealtime
    /// Real implementation would parse Rust source via syn, check for Vec, String, HashMap, Box, Arc clone, println!, format!, filesystem, blocking lock, SystemTime
    pub fn check_hard_realtime(&mut self, callback_name: &str, source_contains: &[&str]) {
        for pattern in source_contains {
            match *pattern {
                "println!" => self.errors.push(format!("ERROR RT001: HardRealtime callback {} calls std::println! — non-deterministic I/O", callback_name)),
                "Vec::new" | "Vec::push" => self.errors.push(format!("ERROR RT002: HardRealtime callback {} allocates Vec — forbidden", callback_name)),
                "String::" => self.errors.push(format!("ERROR RT002: HardRealtime callback {} allocates String", callback_name)),
                "SystemTime::now" => self.warnings.push(format!("WARNING RT003: SystemTime used in realtime path {} — should use MonotonicInstant", callback_name)),
                "HashMap" => self.errors.push(format!("ERROR RT004: HardRealtime callback {} uses HashMap — may allocate", callback_name)),
                _ => {}
            }
        }
    }

    pub fn has_errors(&self) -> bool { !self.errors.is_empty() }

    pub fn print(&self) {
        for e in &self.errors { println!("{}", e); }
        for w in &self.warnings { println!("{}", w); }
        if self.errors.is_empty() {
            println!("Realtime lint: No hard realtime violations found (for checked patterns)");
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_executor_priority_ordering() {
        let mut executor = Executor::new();
        let low = CallbackDescriptor { id: TaskId(0), name: "low".into(), execution_class: ExecutionClass::Normal, priority: 10, deadline: None, period: None, cpu_affinity: None };
        let high = CallbackDescriptor { id: TaskId(0), name: "high".into(), execution_class: ExecutionClass::HardRealtime, priority: 200, deadline: Some(Duration::from_micros(1000)), period: None, cpu_affinity: None };

        let low_id = executor.register(low);
        let high_id = executor.register(high);

        // Manually wake both
        executor.wake(low_id);
        executor.wake(high_id);

        // High priority should run first
        let first = executor.run_once_with(|_| Duration::from_micros(10)).unwrap();
        assert_eq!(first.0, high_id);

        let second = executor.run_once_with(|_| Duration::from_micros(10)).unwrap();
        assert_eq!(second.0, low_id);
    }

    #[test]
    fn test_executor_deadline_monitoring() {
        let mut executor = Executor::new();
        let desc = CallbackDescriptor {
            id: TaskId(0),
            name: "control_loop".into(),
            execution_class: ExecutionClass::HardRealtime,
            priority: 200,
            deadline: Some(Duration::from_micros(1000)),
            period: Some(Duration::from_millis(1)),
            cpu_affinity: Some(vec![2,3]),
        };
        let id = executor.register(desc);
        executor.wake(id);

        // Simulate callback taking 1.5ms > 1ms deadline
        executor.run_once_with(|_| Duration::from_micros(1500));

        let stats = executor.get_stats(id).unwrap();
        assert_eq!(stats.deadline_misses, 1);
        assert_eq!(stats.execution_count, 1);
    }

    #[test]
    fn test_realtime_lint() {
        let mut lint = RealtimeLint::new();
        lint.check_hard_realtime("control_loop", &["println!", "Vec::new"]);
        assert!(lint.has_errors());
        assert!(lint.errors.iter().any(|e| e.contains("RT001")));
        assert!(lint.errors.iter().any(|e| e.contains("RT002")));
    }
}
